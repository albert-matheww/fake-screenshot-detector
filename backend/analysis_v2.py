"""Screenshot authenticity analysis (v2).

Pipeline
  1. OCR -> word boxes
  2. word-level rendering-consistency features (textforensics) -> P(word was edited)
  3. rule-based semantic checks (semantic): file metadata, generator watermarks,
     arithmetic / date / checksum contradictions
  4. verdict with three tiers, localised regions and plain-language reasons

The verdict is deliberately NOT a binary real/fake label. A screenshot that was rendered
natively with fake content (browser DevTools edit, a generator site, an AI image model)
leaves no rendering inconsistency, so "no evidence of editing" is never reported as
"authentic" - see LIMITATIONS, which is returned with every response.
"""
from __future__ import annotations

import hashlib
import io
import json
import os
import time
from typing import Any, Dict, List, Optional

import numpy as np
from PIL import Image, ImageOps

import semantic
import textforensics as tf

_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "model_data")
_MODEL = None
_META: Dict[str, Any] = {}
_LOAD_ERROR: Optional[str] = None

try:
    import joblib

    _mp, _jp = os.path.join(_DIR, "word_gbm.joblib"), os.path.join(_DIR, "word_gbm_meta.json")
    if os.path.exists(_mp) and os.path.exists(_jp):
        _MODEL = joblib.load(_mp)
        with open(_jp) as fh:
            _META = json.load(fh)
        if _META.get("feature_names") != tf.FEATURE_NAMES:
            raise RuntimeError("model feature list does not match textforensics.FEATURE_NAMES - retrain the model")
except Exception as exc:  # noqa: BLE001
    _MODEL, _LOAD_ERROR = None, str(exc)

THR_LO = float(_META.get("thresholds", {}).get("5%", 0.4))   # ~5% false alarms on authentic validation images
THR_HI = float(_META.get("thresholds", {}).get("1%", 0.8))   # ~1%
MIN_MEASURED_WORDS = 6

LIMITATIONS = [
    "This tool finds *inconsistencies left by editing*. It cannot detect a screenshot that was rendered with fake "
    "content from the start (edited in a browser's DevTools, produced by a fake-receipt generator site, or "
    "generated by an AI image model).",
    "'No evidence of editing' is not proof that a screenshot is genuine. Confirm important claims with the "
    "issuer (bank, payment app, sender).",
    "Heavy re-compression or downscaling (e.g. after several re-shares) removes much of the evidence it relies on.",
]

SEVERITY_ORDER = {"high": 3, "medium": 2, "low": 1}


def model_info() -> Dict[str, Any]:
    m = _META.get("metrics", {})
    return {
        "loaded": _MODEL is not None, "error": _LOAD_ERROR,
        "train_images": _META.get("train_images"), "train_words": _META.get("train_words"),
        "thresholds": {"suspicious": THR_LO, "evidence": THR_HI},
        "test_auc": (m.get("test") or {}).get("auc"),
        "feature_count": len(tf.FEATURE_NAMES),
    }


def _risk(prob: float) -> float:
    """Map the model's max-word probability to a 0-1 'risk' that increases monotonically and puts the
    two operating thresholds at 0.40 and 0.70 so the UI gauge matches the verdict tiers."""
    if prob <= THR_LO:
        return 0.40 * prob / max(THR_LO, 1e-6)
    if prob <= THR_HI:
        return 0.40 + 0.30 * (prob - THR_LO) / max(THR_HI - THR_LO, 1e-6)
    return min(1.0, 0.70 + 0.30 * (prob - THR_HI) / max(1.0 - THR_HI, 1e-6))


def analyze_image_bytes(raw_bytes: bytes, config=None) -> Dict[str, Any]:
    t0 = time.time()
    image = Image.open(io.BytesIO(raw_bytes))
    image.load()
    fmt = image.format
    # browsers display the EXIF-rotated image; report region coordinates in that same frame
    rgb = ImageOps.exif_transpose(image).convert("RGB")
    W, H = rgb.size
    sha = hashlib.sha256(raw_bytes).hexdigest()

    words = tf.ocr_words(rgb)
    X, kept, info = tf.image_word_features(rgb, words)
    analysable = X.shape[0] >= MIN_MEASURED_WORDS and _MODEL is not None

    probs = np.zeros(0)
    regions: List[Dict[str, Any]] = []
    if X.shape[0] and _MODEL is not None:
        probs = _MODEL.predict_proba(X)[:, 1]
        order = np.argsort(-probs)
        for i in order[:10]:
            if probs[i] < THR_LO * 0.75:
                break
            wd = kept[i]
            regions.append({
                "x": int(wd["left"]), "y": int(wd["top"]), "w": int(wd["width"]), "h": int(wd["height"]),
                "text": wd["text"], "score": round(float(probs[i]), 4),
                "level": "evidence" if probs[i] >= THR_HI else ("suspicious" if probs[i] >= THR_LO else "weak"),
                "reasons": tf.explain_word(X[i]),
            })
    top_prob = float(probs.max()) if len(probs) else 0.0

    findings = semantic.run_all(rgb, words)
    findings.sort(key=lambda f: -SEVERITY_ORDER.get(f["severity"], 0))
    # a rule finding that points at a specific number is also marked on the image - as a RULE result (no probability)
    for f in findings:
        box = (f.get("evidence") or {}).get("box")
        if box and f["id"] == "layout.column_off_grid":
            regions.append({"x": int(box[0]), "y": int(box[1]), "w": int(box[2]), "h": int(box[3]),
                            "text": f["evidence"].get("text", ""), "score": 0.0, "source": "rule",
                            "level": "suspicious", "reasons": [f["message"]]})
    sem_sev = max((SEVERITY_ORDER[f["severity"]] for f in findings), default=0)

    if top_prob >= THR_HI or sem_sev >= 3:
        verdict, label = "evidence_of_editing", "Evidence of editing found"
    elif top_prob >= THR_LO or sem_sev == 2:
        verdict, label = "suspicious", "Suspicious - review recommended"
    elif analysable:
        verdict, label = "no_evidence", "No evidence of editing found"
    else:
        verdict, label = "inconclusive", "Not enough readable text to analyse"

    risk = _risk(top_prob)
    if sem_sev >= 3:
        risk = max(risk, 0.85)
    elif sem_sev == 2:
        risk = max(risk, 0.55)

    reasons: List[str] = []
    for r in regions:
        if r["level"] in ("evidence", "suspicious") and r.get("source") != "rule":   # rule regions: the finding says it
            why = "; ".join(r["reasons"][:2]) or "its rendering is inconsistent with the surrounding text"
            reasons.append(f'The word "{r["text"]}" looks edited: {why}.')
    reasons += [f["message"] for f in findings if f["severity"] in ("high", "medium")]
    if verdict == "no_evidence":
        reasons.append(f"{X.shape[0]} words were checked for rendering inconsistencies and none stood out.")
    if verdict == "inconclusive":
        reasons.append(f"Only {X.shape[0]} words could be measured (need {MIN_MEASURED_WORDS}+)."
                       if _MODEL is not None else "The text-edit model is not loaded.")

    return {
        "verdict": verdict, "verdict_label": label, "risk_score": round(risk, 4),
        "reasons": reasons[:8], "regions": regions, "findings": findings,
        "limitations": LIMITATIONS,
        "image": {"width": W, "height": H, "format": fmt},
        "stats": {"ocr_words": info["ocr_words"], "measured_words": int(X.shape[0]),
                  "top_word_probability": round(top_prob, 4),
                  "thresholds": {"suspicious": THR_LO, "evidence": THR_HI}},
        "meta": {"sha256": sha, "processing_ms": round((time.time() - t0) * 1000, 1),
                 "model": "word-level gradient boosting over rendering-consistency features + rule checks (v2)"},
        # backwards-compatible aliases for older clients
        "fake_score": round(risk, 4), "is_fake": verdict == "evidence_of_editing",
        "verdict_text": label,
    }
