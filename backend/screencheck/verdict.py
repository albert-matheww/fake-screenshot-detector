"""Fail-safe verdict policy.

Rules
  * Only checks whose gate is "live" can move the verdict. Advisory checks are listed but never count.
  * Nothing ever yields "authentic". The best outcome is "no inconsistency found by the checks that could examine it".
  * Any doubt moves the verdict towards "inconclusive", never towards "clear":
      - the type is unknown or the routers disagree,
      - an advisory check raised a signal,
      - too few live checks could look at the screenshot.
"""
from __future__ import annotations

from typing import Any, Dict, List

# A screenshot can only be reported as 'no inconsistency found' if a calibrated check of EACH kind could examine it:
# a content check (what it says) and a visual check (how it looks). File metadata alone never clears an image.
NEED_CATEGORIES = ('content', 'visual')

LIMITATIONS = [
    "The checks look for inconsistencies. A screenshot rendered with false content from the start (edited in a browser's "
    "developer tools, made by a fake-receipt site, or generated by an AI model) can pass every check.",
    "A careful edit that matches the surrounding font, size and colour, and keeps the content consistent, leaves nothing for "
    "these checks to find. 'No inconsistency found' is therefore not proof that a screenshot is genuine.",
    "Re-compression and down-scaling (for example after sharing on a messaging app) remove most pixel-level evidence.",
    "For anything that matters, confirm the claim with the issuer: the bank or payment app (transaction ID), the seller, or the sender.",
]

VERIFY_STEPS = [
    "Ask the issuer (bank, payment app, seller or sender) to confirm the transaction or message using its reference number.",
    "Ask for the original file, or for the same page captured again by the sender in front of you.",
    "If you hold a genuine copy, use compare mode to see exactly what differs.",
]

LABELS = {
    "evidence_of_editing": "Inconsistency found",
    "suspicious": "Possible inconsistency - review recommended",
    "no_evidence": "No inconsistency found by the checks that could run",
    "inconclusive": "Inconclusive - verify with the issuer",
}


def decide(route: Dict[str, Any], checks: List[Dict[str, Any]], words_read: int) -> Dict[str, Any]:
    live_find = [c for c in checks if c["gate"]["status"] == "live" and c["status"] == "finding"]
    live_clear = [c for c in checks if c["gate"]["status"] == "live" and c["status"] == "clear"]
    adv_find = [c for c in checks if c["gate"]["status"] != "live" and c["status"] == "finding"]
    na = [c for c in checks if c["status"] == "not_applicable"]
    reasons: List[str] = []

    top = max((3 if c["severity"] == "high" else 2 if c["severity"] == "medium" else 1 for c in live_find), default=0)
    if top == 3:
        verdict = "evidence_of_editing"
    elif top == 2:
        verdict = "suspicious"
    else:
        verdict = None
    for c in live_find:
        reasons += [f["message"] for f in c["findings"] if f["severity"] in ("high", "medium")]
    if verdict is None and live_find:
        reasons += [f["message"] for c in live_find for f in c["findings"]][:3]

    caveats: List[str] = []
    if route["type"] == "unknown":
        caveats.append("The type of screenshot could not be determined with confidence, so type-specific checks were not run.")
    elif route["status"] == "tentative":
        caveats.append(f"The screenshot type ({route['label']}) is only tentative: the two routers did not both support it.")
    if not route.get("router_validated") and route["type"] != "unknown":
        caveats.append("The type router has not been validated on real screenshots, so type-specific checks are disabled.")
    if adv_find:
        caveats.append("Advisory checks (not yet calibrated, so not counted) raised signals: "
                       + "; ".join(c["name"] for c in adv_find) + ".")
    cats_clear = {c["category"] for c in live_clear}
    missing = [k for k in NEED_CATEGORIES if k not in cats_clear]
    if missing:
        caveats.append("No calibrated " + " or ".join(missing) + " check could examine this screenshot"
                       + (" (visual checks are not yet calibrated on enough real reference screenshots)." if "visual" in missing else "."))
    if words_read < 15:
        caveats.append("Very little text could be read.")

    if verdict is None:
        doubtful = (route["type"] == "unknown" or bool(adv_find) or bool(missing) or words_read < 15)
        verdict = "inconclusive" if doubtful else "no_evidence"
    risk = {"evidence_of_editing": 0.88, "suspicious": 0.58, "inconclusive": 0.42, "no_evidence": 0.15}[verdict]
    if verdict == "no_evidence":
        reasons.append(f"{len(live_clear)} calibrated check(s), including content and visual checks, examined the screenshot and none found a contradiction.")
    return {"verdict": verdict, "verdict_label": LABELS[verdict], "risk_score": risk, "reasons": (reasons + caveats)[:8],
            "caveats": caveats,
            "coverage": {"live_findings": len(live_find), "live_clear": len(live_clear), "advisory_findings": len(adv_find),
                         "not_applicable": len(na), "checks_run": len(checks)}}
